#!/usr/bin/env python3
"""The per-class seed: models/domain-neutral.m with every class in its own container
(<Class>Service) and every schema on its own database server (<Class>Database); mechanisms, sagas and
everything else stay the neutral seed's (every call synchronous, every saga choreographed), but the in-transaction
steps, which are synchronous steps when the classes are apart. A start from the
domain alone, at the fine-grained end of the cut instead of the monolith.

    [ARCH_CASE=misarch] core/generator/perclass_seed.py   ->  the case's models/domain-perclass.m

It derives the seed from the generated neutral model and changes only the 64 placement links.
"""
import argparse
import re
import sys
from pathlib import Path

P = Path(__file__).resolve().parents[2]           # the repository root
sys.path.insert(0, str(P / "core" / "tools"))
import case  # noqa: E402

argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
models = case.load().path("mdeo.models")      # the case's base models (ARCH_CASE, default misarch)
src = models / "domain-neutral.m"
out = models / "domain-perclass.m"
text = src.read_text()
containers = set(re.findall(r"^(\w+) : ResourceContainer \{", text, re.M))
moved = 0


def place(m):
    global moved
    cls, db = m.group(1), m.group(2)
    target = f"{cls}Database" if db else f"{cls}Service"
    if target not in containers:
        raise SystemExit(f"no container {target} for alloc_Assembly_{cls}{db or ''}")
    moved += 1
    return f"alloc_Assembly_{cls}{db or ''}.resourceContainer -- {target}"


text = re.sub(r"^alloc_Assembly_(\w+?)(Db)?\.resourceContainer -- (?:MonolithService|SharedDatabase)$", place, text, flags=re.M)
# every class apart: no effect step can join its caller's transaction, so the neutral seed's
# in-transaction steps are synchronous steps here (the realisation would make them so anyway)
text, joined = re.subn(r"^(site_\w+)\.mechanism -- inTx$", r"\1.mechanism -- sync", text, flags=re.M)
old = """// domain class, the service cut is the allocation. Seed: a neutral start: every class in one
// container, every schema on the shared database server, every call synchronous, every saga
// choreographed."""
new = """// domain class, the service cut is the allocation. Seed: one service per class: every class in its
// own container, every schema on its own database server, every call synchronous, every saga
// choreographed (core/generator/perclass_seed.py from domain-neutral.m: only the placement
// differs)."""
if old not in text:
    raise SystemExit("header of the neutral model changed")
text = text.replace(old, new)
# derive.py's generator line (wrapped; its GENERATED) becomes this script's
text, n = re.subn(r"^// Generated by core/generator/derive\.py .*?not this file\.\n",
                  "// Generated by core/generator/perclass_seed.py from the neutral model; edit the generators, not\n"
                  "// this file.\n", text, count=1, flags=re.M | re.S)
if n != 1:
    raise SystemExit("generator line of the neutral model changed")
out.write_text(text)
print(f"{out.relative_to(P)}: {moved} placement links moved, {joined} in-transaction steps made synchronous")

#!/usr/bin/env bash
# Generates optimize/domain/detail.fn: the request part of transform/metrics.fn
# (everything up to its "end of the request" line, copied verbatim: scaling groups, overrides,
# load profile, percentiles, simulation and HPA settings and detailRequest()), so that the explorer's detail run
# (core/tools/design_detail.sh) simulates exactly the request the search evaluated. detailRequest()
# prints it, one line per item:
#   REQUEST warmUpS=.. durationS=.. binS=.. ...     (the detail request's settings, key=value)
#   PERCENTILE <percent>
#   GROUP <container> <min> <max> <target> <initial> <startup s> <scale-down s> <cpu request>
#   OVERRIDE <container> <replicas> <rate>          (the container's CPU)
#   STEP <scenario | *> <time s> <factor>
# (entity names; design_detail.sh maps them to the model's instance names).
set -euo pipefail
P="$(cd "$(dirname "$0")/../.." && pwd)"
src="$P/core/mdeo/transform/metrics.fn"
end=$(grep -n "^// ═══ end of the request" "$src" | head -1 | cut -d: -f1)
{
    echo "// GENERATED by core/tools/gen_detail_fn.sh from core/mdeo/transform/metrics.fn (lines 1-$((end - 1))); do not edit."
    sed -n "1,$((end - 1))p" "$src" | sed "s#^using \"../metamodel/#using \"../../metamodel/#"
} > "$P/core/mdeo/optimize/domain/detail.fn"
echo "core/mdeo/optimize/domain/detail.fn: $(wc -l < "$P/core/mdeo/optimize/domain/detail.fn") lines"

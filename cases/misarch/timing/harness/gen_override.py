#!/usr/bin/env python3
"""Generate the timing compose override (README.md §2.3) from a resolved misarch-kotlin topology.

    gen_override.py [--topology plain] [--out FILE]

The override is derived from `docker compose config` of the topology, not from a hand-written list, so every app
and database the topology has gets the switches:
  - every app (image misarch-kotlin/*): OTLP trace export, a trace-id-ratio sampler whose ratio comes from
    TIMING_SAMPLER_ARG (default 0.1, the campaign's sampler), GraphQL data-fetcher spans,
    MISARCH_TIMING_SPANS=true (the instrumentation build's manual spans; inert on images without them), DebugNonSafepoints appended to
    the app's own JAVA_OPTS expression (exact profiler frames), the async-profiler mount at
    /opt/async-profiler (ro) and the results dir at /timing;
  - every Postgres 16 (image postgres:16; Keycloak's postgres:16-alpine is left alone): pg_stat_statements
    preloaded, track=top, max=10000, track_io_timing=on.
  - Zipkin (in-memory): heap 4 GB and MEM_MAX_SPANS 3,000,000 (the default heap overflows at sampling 1).
Dapr tracing is not part of the override: timing-up.sh sets TRACING=1 (dapr-config.yaml, sampling 1).
Values are compose interpolations, so timing-up.sh selects them per block without regenerating the file.
"""
import argparse
import json
import os
import subprocess
import sys

TIMING = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def _checkout(root, name):
    """The submodule <name>/ of the repository if it is checked out, else ../<name> beside the repository."""
    sub = os.path.join(root, name)
    return sub if os.path.isdir(sub) and os.listdir(sub) else os.path.join(os.path.dirname(root), name)


KOTLIN = os.path.join(os.environ.get("MISARCH_KOTLIN_REPO", _checkout(os.path.normpath(os.path.join(TIMING, "..", "..", "..")), "misarch-kotlin")),
                      "deploy", "compose")
FILES = {"plain": ["docker-compose.yaml"]}

APP_ENV = [
    ("OTEL_TRACES_EXPORTER", "otlp"),
    ("OTEL_TRACES_SAMPLER", "traceidratio"),
    ("OTEL_TRACES_SAMPLER_ARG", "${TIMING_SAMPLER_ARG:-0.1}"),
    ("OTEL_INSTRUMENTATION_GRAPHQL_DATA_FETCHER_ENABLED", "true"),
    ("MISARCH_TIMING_SPANS", "true"),
    ("MISARCH_PROFILER", "${TIMING_PROFILER_AGENT:-}"),
]
# appended to each app's own JAVA_OPTS expression
EXTRA_JAVA_OPTS = "${TIMING_EXTRA_JAVA_OPTS:--XX:+UnlockDiagnosticVMOptions -XX:+DebugNonSafepoints}"
APP_VOLUMES = [
    "${TIMING_ASPROF_DIR:?set TIMING_ASPROF_DIR to an async-profiler 4.2.1 directory (timing/local.env)}:/opt/async-profiler:ro",
    # timing-up.sh sets TIMING_OUT; the default is relative to the compose project directory (misarch-kotlin/deploy/compose)
    "${TIMING_OUT:-" + os.path.relpath(os.path.join(TIMING, "raw", "_asprof"), KOTLIN) + "}:/timing",
]
PG_COMMAND = ["postgres", "-c", "shared_preload_libraries=pg_stat_statements", "-c", "pg_stat_statements.track=top",
              "-c", "pg_stat_statements.max=10000", "-c", "track_io_timing=on"]


def resolved(topology):
    args = ["docker", "compose"]
    for f in FILES[topology]:
        args += ["-f", f]
    out = subprocess.run(args + ["config", "--no-interpolate", "--format", "json"], cwd=KOTLIN, capture_output=True,
                         text=True)
    if out.returncode:
        sys.exit(out.stderr)
    return json.loads(out.stdout)["services"]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(topology, services):
    apps = sorted(k for k, v in services.items() if v.get("image", "").startswith("misarch-kotlin/"))
    dbs = sorted(k for k, v in services.items() if v.get("image", "") == "postgres:16")
    lines = [f"# Timing switches (architecture-optimization timing/README.md §2.3), topology {topology}.",
             "# Generated by timing/harness/gen_override.py from `docker compose config`; do not edit by hand.",
             "# Apply with timing/timing-up.sh (COMPOSE_FILE=<topology>:<image pins>:<this file>). Without it the stack",
             "# is exactly today's.",
             "x-timing-app-env: &timing-app-env"]
    lines += [f"  {k}: {q(v)}" for k, v in APP_ENV]
    lines += ["x-timing-app-volumes: &timing-app-volumes"]
    lines += [f"  - {q(v)}" for v in APP_VOLUMES]
    lines += ["x-timing-pg-command: &timing-pg-command"]
    lines += [f"  - {q(v)}" for v in PG_COMMAND]
    lines += ["services:"]
    for a in apps:
        java = services[a].get("environment", {}).get("JAVA_OPTS") or ""
        lines += [f"  {a}:", "    environment:", "      <<: *timing-app-env",
                  f"      JAVA_OPTS: {q((java + ' ' + EXTRA_JAVA_OPTS).strip())}", "    volumes: *timing-app-volumes"]
    for d in dbs:
        lines += [f"  {d}:", "    command: *timing-pg-command"]
    if "zipkin-all-in-one" in services:
        # the default heap runs out at sampling 1 (~3,000 traces in 6 min) and a restart loses every span
        lines += ["  zipkin-all-in-one:", "    environment:",
                  '      JAVA_OPTS: "${TIMING_ZIPKIN_JAVA_OPTS:--Xms1g -Xmx4g}"',
                  '      MEM_MAX_SPANS: "${TIMING_ZIPKIN_MAX_SPANS:-3000000}"']
    return "\n".join(lines) + "\n", apps, dbs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--topology", default="plain", choices=sorted(FILES))
    ap.add_argument("--out")
    a = ap.parse_args()
    text, apps, dbs = render(a.topology, resolved(a.topology))
    if a.out:
        open(a.out, "w").write(text)
        print(f"{a.out}: {len(apps)} apps, {len(dbs)} postgres", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
